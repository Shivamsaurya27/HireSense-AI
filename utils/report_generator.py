def generate_ranking_report(
    job_title: str,
    ranked_candidates: list[dict],
    output_path: str,
    summary: Optional[dict] = None,
) -> tuple[bool, Optional[str]]:
    """Generate a batch PDF report summarizing all ranked candidates for
    a job description.

    Expected `ranked_candidates` shape — a list of dicts matching
    `RankedCandidate.to_dict()` from ml/candidate_ranker.py:
        [
            {
                "candidate_id": str, "name": str, "rank": int,
                "total_score": float, "tier": str,
                "score_breakdown": {...same shape as generate_candidate_report...},
                "error": str | None,
            },
            ...
        ]

    `summary` is optional — the output of
    `CandidateRanker.summarize_ranking()` (average score, tier counts,
    etc.) — shown at the top if provided.

    Returns (success, error_message). Never raises.
    """
    try:
        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        styles = _build_styles()
        doc = SimpleDocTemplate(
            str(output_file), pagesize=A4,
            topMargin=18 * mm, bottomMargin=16 * mm,
            leftMargin=18 * mm, rightMargin=18 * mm,
            title=f"HireSense AI Ranking Report - {job_title}",
        )

        story = []
        story.extend(_build_header(styles, "Candidate Ranking Report", job_title))

        if summary:
            story.extend(_build_summary_block(styles, summary))

        story.extend(_build_ranking_table(styles, ranked_candidates))
        story.append(Spacer(1, 14))
        story.extend(_build_disclaimer_block(styles, None))

        doc.build(story)
        logger.info("Ranking report generated: %s", output_file)
        return True, None

    except Exception as exc:  # noqa: BLE001
        logger.exception("Failed to generate ranking report for job '%s'", job_title)
        return False, f"Failed to generate PDF report: {exc}"


def _build_summary_block(styles: dict, summary: dict) -> list:
    rows = [
        ["Total Candidates", str(summary.get("total_candidates", 0))],
        ["Successfully Scored", str(summary.get("scored_candidates", 0))],
        ["Average Score", f"{summary.get('average_score', 0):.1f}/100"],
        ["Top Score", f"{summary.get('top_score', 0):.1f}/100"],
    ]

    tier_counts = summary.get("tier_counts", {})
    if tier_counts:
        tier_summary = ", ".join(f"{tier}: {count}" for tier, count in tier_counts.items())
        rows.append(["Tier Breakdown", tier_summary])

    table = Table(rows, colWidths=[45 * mm, 120 * mm])
    table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.grey),
        ("BACKGROUND", (0, 0), (-1, -1), _COLOR_LIGHT_BG),
        ("BOX", (0, 0), (-1, -1), 0.5, _COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    return [Paragraph("Summary", styles["heading"]), table, Spacer(1, 10)]


def _build_ranking_table(styles: dict, ranked_candidates: list[dict]) -> list:
    if not ranked_candidates:
        return [Paragraph("No candidates to display.", styles["body"])]

    header = ["Rank", "Candidate", "Score", "Tier", "Matched Skills"]
    rows = [header]

    for candidate in ranked_candidates:
        breakdown = candidate.get("score_breakdown") or {}
        skills_details = (
            breakdown.get("components", {}).get("skills", {}).get("details", {})
        )
        matched_count = len(skills_details.get("matched_skills", []))
        required_count = skills_details.get("required_skill_count", 0)

        if candidate.get("error"):
            score_display = "N/A"
            tier_display = "Unscored"
            skills_display = candidate["error"]
        else:
            score_display = f"{candidate.get('total_score', 0):.1f}"
            tier_display = candidate.get("tier", "")
            skills_display = f"{matched_count}/{required_count}" if required_count else str(matched_count)

        rows.append([
            str(candidate.get("rank", "")),
            candidate.get("name", "Unknown"),
            score_display,
            tier_display,
            skills_display,
        ])

    table = Table(rows, colWidths=[15 * mm, 50 * mm, 22 * mm, 32 * mm, 35 * mm])
    style_commands = [
        ("BACKGROUND", (0, 0), (-1, 0), _COLOR_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (0, 0), (0, -1), "CENTER"),
        ("ALIGN", (2, 0), (2, -1), "CENTER"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _COLOR_LIGHT_BG]),
        ("GRID", (0, 0), (-1, -1), 0.5, _COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]

    for row_index, candidate in enumerate(ranked_candidates, start=1):
        if not candidate.get("error"):
            tier_color = _tier_color(candidate.get("tier", ""))
            style_commands.append(
                ("TEXTCOLOR", (3, row_index), (3, row_index), tier_color)
            )
            style_commands.append(("FONTNAME", (3, row_index), (3, row_index), "Helvetica-Bold"))

    table.setStyle(TableStyle(style_commands))

    return [Paragraph("Ranked Candidates", styles["heading"]), table]


