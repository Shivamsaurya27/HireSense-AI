def generate_candidate_report(
    candidate_name: str,
    score_data: dict,
    output_path: str,
    job_title: str = "",
    candidate_id: str = "",
    resume_filename: str = "",
) -> tuple[bool, Optional[str]]:
    """Generate a single-candidate PDF report.

    Expected `score_data` shape (i.e. the output of
    `ATSScoreResult.to_dict()` from ml/ats_scorer.py):
        {
            "total_score": float,
            "components": {
                "skills": {"raw_score": float, "weight_percent": float,
                            "weighted_contribution": float,
                            "details": {"matched_skills": [...],
                                        "missing_skills": [...], ...}},
                "similarity": {...},
                "experience": {...},
                "education": {...},
                "projects": {...},
                "certifications": {...},
            },
            "weights_used": {...},
            "disclaimer": str,
        }

    A "tier" key is optional (e.g. "Strong Match") — if provided it's
    shown next to the score; otherwise it's omitted.

    Returns (success, error_message). Never raises — PDF generation
    failures are caught and reported back as a message.
    """
    try:
        output_file = Path(output_path)
        output_file.parent.mkdir(parents=True, exist_ok=True)

        styles = _build_styles()
        doc = SimpleDocTemplate(
            str(output_file), pagesize=A4,
            topMargin=18 * mm, bottomMargin=16 * mm,
            leftMargin=18 * mm, rightMargin=18 * mm,
            title=f"HireSense AI Report - {candidate_name}",
        )

        story = []
        story.extend(_build_header(styles, "Candidate Compatibility Report", job_title))
        story.extend(_build_candidate_info_block(styles, candidate_name, candidate_id, resume_filename))
        story.extend(_build_score_summary_block(styles, score_data))
        story.extend(_build_component_breakdown_table(styles, score_data))
        story.extend(_build_skills_section(styles, score_data))
        story.append(Spacer(1, 14))
        story.extend(_build_disclaimer_block(styles, score_data.get("disclaimer")))

        doc.build(story)
        logger.info("Candidate report generated: %s", output_file)
        return True, None

    except Exception as exc:  # noqa: BLE001
        logger.exception("Failed to generate candidate report for %s", candidate_name)
        return False, f"Failed to generate PDF report: {exc}"


def _build_header(styles: dict, report_title: str, job_title: str) -> list:
    elements = [
        Paragraph("HireSense AI", styles["title"]),
        Paragraph(report_title, styles["heading"]),
    ]
    if job_title:
        elements.append(Paragraph(f"Position: {job_title}", styles["subtitle"]))
    elements.append(HRFlowable(width="100%", thickness=1, color=_COLOR_BORDER, spaceAfter=10))
    return elements


def _build_candidate_info_block(
    styles: dict, candidate_name: str, candidate_id: str, resume_filename: str
) -> list:
    rows = [["Candidate Name", candidate_name or "N/A"]]
    if candidate_id:
        rows.append(["Candidate ID", candidate_id])
    if resume_filename:
        rows.append(["Resume File", resume_filename])
    rows.append(["Report Generated", get_timestamp().replace("_", " ")])

    table = Table(rows, colWidths=[45 * mm, 120 * mm])
    table.setStyle(TableStyle([
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (0, -1), colors.grey),
        ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("LINEBELOW", (0, -1), (-1, -1), 0.5, _COLOR_BORDER),
    ]))
    return [table, Spacer(1, 12)]


def _build_score_summary_block(styles: dict, score_data: dict) -> list:
    total_score = score_data.get("total_score", 0.0)
    tier = score_data.get("tier")

    elements = [
        Paragraph(format_score(total_score, decimals=1), styles["score_big"]),
    ]
    if tier:
        tier_style = ParagraphStyle(
            "TierColored", parent=styles["tier_label"],
            textColor=_tier_color(tier), fontName="Helvetica-Bold",
        )
        elements.append(Paragraph(tier, tier_style))
    else:
        elements.append(Spacer(1, 10))

    elements.append(
        Paragraph(
            "Overall AI-generated compatibility score (see breakdown and "
            "disclaimer below).",
            styles["small"],
        )
    )
    elements.append(Spacer(1, 8))
    return elements


_COMPONENT_LABELS = {
    "skills": "Skills Match",
    "similarity": "Job Description Similarity",
    "experience": "Experience",
    "education": "Education",
    "projects": "Projects",
    "certifications": "Certifications",
}


def _build_component_breakdown_table(styles: dict, score_data: dict) -> list:
    components = score_data.get("components", {})
    if not components:
        return []

    header = ["Component", "Weight", "Raw Score", "Contribution"]
    rows = [header]

    for key, label in _COMPONENT_LABELS.items():
        component = components.get(key)
        if not component:
            continue
        rows.append([
            label,
            f"{component.get('weight_percent', 0)}%",
            f"{component.get('raw_score', 0):.1f}/100",
            f"{component.get('weighted_contribution', 0):.2f} pts",
        ])

    table = Table(rows, colWidths=[60 * mm, 25 * mm, 35 * mm, 35 * mm])
    style_commands = [
        ("BACKGROUND", (0, 0), (-1, 0), _COLOR_PRIMARY),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("ALIGN", (1, 0), (-1, -1), "CENTER"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, _COLOR_LIGHT_BG]),
        ("GRID", (0, 0), (-1, -1), 0.5, _COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 5),
    ]

    # Color-code the raw score column per row based on its value.
    for row_index, key in enumerate([k for k in _COMPONENT_LABELS if k in components], start=1):
        raw_score = components[key].get("raw_score", 0)
        style_commands.append(
            ("TEXTCOLOR", (2, row_index), (2, row_index), _score_color(raw_score))
        )
        style_commands.append(("FONTNAME", (2, row_index), (2, row_index), "Helvetica-Bold"))

    table.setStyle(TableStyle(style_commands))

    return [
        Paragraph("Score Breakdown", styles["heading"]),
        table,
        Spacer(1, 4),
    ]


def _build_skills_section(styles: dict, score_data: dict) -> list:
    skills_component = score_data.get("components", {}).get("skills", {})
    details = skills_component.get("details", {})
    matched = details.get("matched_skills", [])
    missing = details.get("missing_skills", [])

    elements = [Paragraph("Skills Analysis", styles["heading"])]

    matched_style = ParagraphStyle(
        "MatchedSkills", parent=styles["body"], textColor=_COLOR_SUCCESS,
    )
    missing_style = ParagraphStyle(
        "MissingSkills", parent=styles["body"], textColor=_COLOR_DANGER,
    )

    if matched:
        elements.append(Paragraph(
            f"<b>Matched Skills ({len(matched)}):</b> " + ", ".join(matched),
            matched_style,
        ))
    else:
        elements.append(Paragraph("<b>Matched Skills:</b> None detected.", styles["body"]))

    elements.append(Spacer(1, 4))

    if missing:
        elements.append(Paragraph(
            f"<b>Missing Skills ({len(missing)}):</b> " + ", ".join(missing),
            missing_style,
        ))
    else:
        elements.append(Paragraph(
            "<b>Missing Skills:</b> None — all required skills were found.",
            styles["body"],
        ))

    return elements


def _build_disclaimer_block(styles: dict, disclaimer: Optional[str]) -> list:
    text = disclaimer or DISCLAIMER_TEXT
    box_table = Table([[Paragraph(f"<b>Disclaimer:</b> {text}", styles["disclaimer"])]],
                       colWidths=[174 * mm])
    box_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), _COLOR_LIGHT_BG),
        ("BOX", (0, 0), (-1, -1), 0.5, _COLOR_BORDER),
        ("TOPPADDING", (0, 0), (-1, -1), 8),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
        ("LEFTPADDING", (0, 0), (-1, -1), 8),
        ("RIGHTPADDING", (0, 0), (-1, -1), 8),
    ]))
    return [box_table]


