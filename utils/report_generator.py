DISCLAIMER_TEXT = (
    "This compatibility score is generated by HireSense AI for "
    "educational/project demonstration purposes only. It is NOT an "
    "official ATS (Applicant Tracking System) algorithm and should not "
    "be used as the sole basis for real hiring decisions. Methodology "
    "and weights are transparent and configurable."
)

# Brand-ish color palette (kept simple/professional — this is a
# functional report, not a marketing asset).
_COLOR_PRIMARY = colors.HexColor("#1F3A5F")
_COLOR_ACCENT = colors.HexColor("#2E86AB")
_COLOR_SUCCESS = colors.HexColor("#2E7D32")
_COLOR_WARNING = colors.HexColor("#B8860B")
_COLOR_DANGER = colors.HexColor("#C62828")
_COLOR_LIGHT_BG = colors.HexColor("#F2F5F8")
_COLOR_BORDER = colors.HexColor("#D0D7DE")


def _tier_color(tier: str) -> colors.Color:
    """Map a recommendation tier string to a display color."""
    mapping = {
        "Strong Match": _COLOR_SUCCESS,
        "Good Match": _COLOR_ACCENT,
        "Moderate Match": _COLOR_WARNING,
        "Weak Match": _COLOR_DANGER,
        "Unscored": colors.grey,
    }
    return mapping.get(tier, _COLOR_ACCENT)


def _score_color(score: float) -> colors.Color:
    """Map a raw 0-100 score to a display color (used for component
    score cells in tables).
    """
    if score >= 75:
        return _COLOR_SUCCESS
    if score >= 55:
        return _COLOR_ACCENT
    if score >= 35:
        return _COLOR_WARNING
    return _COLOR_DANGER


def _build_styles() -> dict:
    """Build the paragraph style set shared by all reports in this
    module. Centralized so both report types look visually consistent.
    """
    base = getSampleStyleSheet()

    styles = {
        "title": ParagraphStyle(
            "ReportTitle", parent=base["Title"],
            fontSize=20, textColor=_COLOR_PRIMARY, spaceAfter=4,
        ),
        "subtitle": ParagraphStyle(
            "ReportSubtitle", parent=base["Normal"],
            fontSize=11, textColor=colors.grey, spaceAfter=14,
        ),
        "heading": ParagraphStyle(
            "SectionHeading", parent=base["Heading2"],
            fontSize=13, textColor=_COLOR_PRIMARY,
            spaceBefore=14, spaceAfter=6,
        ),
        "body": ParagraphStyle(
            "Body", parent=base["Normal"],
            fontSize=10, leading=14, alignment=TA_LEFT,
        ),
        "small": ParagraphStyle(
            "Small", parent=base["Normal"],
            fontSize=8, leading=11, textColor=colors.grey,
        ),
        "score_big": ParagraphStyle(
            "ScoreBig", parent=base["Normal"],
            fontSize=32, leading=38, alignment=TA_CENTER, textColor=_COLOR_PRIMARY,
            spaceAfter=6,
        ),
        "tier_label": ParagraphStyle(
            "TierLabel", parent=base["Normal"],
            fontSize=12, alignment=TA_CENTER, spaceAfter=10,
        ),
        "disclaimer": ParagraphStyle(
            "Disclaimer", parent=base["Normal"],
            fontSize=8, leading=11, textColor=colors.grey,
            borderPadding=6,
        ),
    }
    return styles


