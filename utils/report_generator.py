"""
utils/report_generator.py
---------------------------
PDF Report Generation Module for HireSense AI.

Generates polished, human-readable PDF reports from the JSON-like result
dictionaries produced by `ml/ats_scorer.py` and `ml/candidate_ranker.py`
(specifically, from calling `.to_dict()` on their result dataclasses).

This module is intentionally decoupled from the ml/ package — it accepts
plain dicts matching documented shapes rather than importing the
dataclasses directly, so it can be tested/used independently and avoids
any risk of circular imports. See the docstrings of each function for
the exact expected dict shape.

Two report types are supported:
    1. Individual Candidate Report — one candidate's full score breakdown.
    2. Batch Ranking Report — a summary table of all ranked candidates
       for a given job description.

Depends on `reportlab` (pure Python, no external binaries needed).
"""

